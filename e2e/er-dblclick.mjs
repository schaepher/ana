import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto('http://localhost:8096/er.html');
await p.waitForSelector('#svg-wrap svg', { timeout: 20000 });
await p.waitForTimeout(400);
const initPaths = await p.$$eval('#svg-wrap svg path', els => els.filter(e => (e.getAttribute('d')||'').startsWith('M')).length);
console.log('init paths:', initPaths);
await (await p.$('rect.tbl[data-tbl="mm_member"]')).dblclick();
await p.waitForTimeout(400);
const selPaths = await p.$$eval('#svg-wrap svg path', els => els.filter(e => (e.getAttribute('d')||'').startsWith('M')).length);
const info1 = await p.textContent('#info');
console.log('after dblclick paths:', selPaths, '|', info1);
await p.screenshot({ path: '/tmp/er-selected.png' });
// 嵌套画法双击 mm_balance_log（10 条关联）
await p.click('#mode-nested');
await p.waitForSelector('#svg-wrap rect.nest-tbl', { timeout: 10000 });
await p.waitForTimeout(300);
await (await p.$('rect.nest-tbl[data-tbl="mm_balance_log"]')).dblclick();
await p.waitForTimeout(400);
const nestedPaths = await p.$$eval('#svg-wrap svg path', els => els.filter(e => (e.getAttribute('d')||'').startsWith('M')).length);
const info2 = await p.textContent('#info');
console.log('nested after dblclick:', nestedPaths, '|', info2);
await p.screenshot({ path: '/tmp/er-selected-nested.png' });
// 取消
await (await p.$('rect.nest-tbl[data-tbl="mm_balance_log"]')).dblclick();
await p.waitForTimeout(400);
const cleared = await p.$$eval('#svg-wrap svg path', els => els.filter(e => (e.getAttribute('d')||'').startsWith('M')).length);
console.log('after 2nd dblclick paths:', cleared);
await b.close();
